-- Financial Cockpit: planning, account balances and financial goals
-- Safe to run more than once. Run in Supabase SQL Editor before deploying this branch.

alter table public.accounts
    add column if not exists account_number text,
    add column if not exists current_balance numeric(14,2),
    add column if not exists balance_as_of date,
    add column if not exists savings_purpose text,
    add column if not exists is_liquid boolean not null default true;

create table if not exists public.financial_goals (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    name text not null,
    goal_type text not null default 'savings',
    target_amount numeric(14,2) not null default 0,
    current_amount numeric(14,2) not null default 0,
    target_date date,
    monthly_contribution numeric(14,2) not null default 0,
    linked_account_id bigint,
    notes text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.financial_goals enable row level security;

drop policy if exists "Users manage own financial goals" on public.financial_goals;
create policy "Users manage own financial goals"
    on public.financial_goals
    for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

create index if not exists financial_goals_user_id_idx
    on public.financial_goals(user_id);

-- Period-specific budgets preserve the current monthly budgets table.
create table if not exists public.budget_plans (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    category text not null,
    period_type text not null check (period_type in ('month', 'quarter', 'year', 'custom')),
    period_start date not null,
    period_end date not null,
    amount numeric(14,2) not null default 0,
    status text not null default 'draft' check (status in ('draft', 'active')),
    source text not null default 'manual',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (period_end >= period_start)
);

alter table public.budget_plans enable row level security;

drop policy if exists "Users manage own budget plans" on public.budget_plans;
create policy "Users manage own budget plans"
    on public.budget_plans
    for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

create index if not exists budget_plans_user_period_idx
    on public.budget_plans(user_id, period_start, period_end);
